#!/usr/bin/env python3
"""lctablegen.py ORACLE-ALL.DUMP ORACLE.DUMP NITRO-ALL.DUMP NITRO.DUMP LOCALES OUT.h GAPS.txt
Generate the expectation tables of kernel32_apitest LocaleTable.c from ldump output measured on Windows 10 22H2
(oracle).  A row is kept when nitro already agrees with the oracle; the rest goes to GAPS.txt.
ORACLE-ALL/NITRO-ALL: ldump of the locales in LOCALES; ORACLE/NITRO: ldump -N names.txt (the name functions)."""
import sys, re, collections
sys.path.insert(0, '.')
import lcdiff

UNESC = lambda s: re.sub(r'\\u([0-9a-f]{4})', lambda m: chr(int(m.group(1), 16)), s)

def lit(s):
    """Wide C string literal; an \\x escape is closed off from a following hex digit by a new literal"""
    if s == '': return 'L""'
    out = []; cur = ''
    hexd = '0123456789abcdefABCDEF'
    for i, ch in enumerate(s):
        if 0x20 <= ord(ch) < 0x7f and ch not in '"\\':
            cur += ch
        elif ch in '"\\':
            cur += '\\' + ch
        else:
            cur += '\\x%04x' % ord(ch)
            if i + 1 < len(s) and s[i + 1] in hexd:
                out.append(cur); cur = ''
    if cur: out.append(cur)
    return ' '.join('L"%s"' % p for p in out)

def main():
    oa = lcdiff.load(sys.argv[1]); on = lcdiff.load(sys.argv[2])
    na = lcdiff.load(sys.argv[3]); nn = lcdiff.load(sys.argv[4])
    locales = open(sys.argv[5]).read().split()
    out, gaps = sys.argv[6], open(sys.argv[7], 'w')
    kept = collections.Counter(); gap = collections.Counter()
    def agree(k, v, tag):
        if k in na and na[k] == v:
            kept[tag] += 1; return True
        gap[tag] += 1
        gaps.write('%s\t%s\t| windows: %s | nitro: %s\n' % (tag, '\t'.join(k[1:]), v, na.get(k)))
        return False
    f = open(out, 'w', encoding='ascii')
    f.write('/* Generated by lctablegen.py from the output of ldump on Windows 10 22H2 (build 19045); do not edit.\n'
            ' * The rows are the values on which nitro agrees with Windows; the others are listed in the ticket. */\n\n')
    # LI strings
    f.write('static const LT_STRING g_LocaleStrings[] =\n{\n')
    for n in locales:
        for k in sorted((k for k in oa if k[0] == 'LI' and k[1] == n), key=lambda k: int(k[2], 16)):
            t = int(k[2], 16); v = oa[k]
            if v[0] == 'ERR' or t == 0x58: continue
            val = UNESC(v[1])
            if '\0' in val: continue
            if not agree(k, v, 'LI'): continue
            f.write('    { L"%s", 0x%x, %s },\n' % (n, t, lit(val)))
    f.write('};\n\n')
    f.write('static const LT_NUMBER g_LocaleNumbers[] =\n{\n')
    for n in locales:
        for k in sorted((k for k in oa if k[0] == 'LN' and k[1] == n), key=lambda k: int(k[2], 16)):
            v = oa[k]
            if not agree(k, v, 'LN'): continue
            f.write('    { L"%s", 0x%x, %s },\n' % (n, int(k[2], 16), v[0]))
    f.write('};\n\n')
    f.write('static const LT_STRING g_GenitiveMonths[] =\n{\n')
    for n in locales:
        for k in sorted((k for k in oa if k[0] == 'LG' and k[1] == n), key=lambda k: int(k[2], 16)):
            v = oa[k]
            if not agree(k, v, 'LG'): continue
            f.write('    { L"%s", 0x%x, %s },\n' % (n, int(k[2], 16), lit(UNESC(v[1]))))
    f.write('};\n\n')
    f.write('static const LT_CALSTRING g_CalendarStrings[] =\n{\n')
    for n in locales:
        for k in sorted((k for k in oa if k[0] == 'CI' and k[1] == n), key=lambda k: (int(k[2]), int(k[3]))):
            v = oa[k]
            if v[0] == 'ERR': continue
            if not agree(k, v, 'CI'): continue
            f.write('    { L"%s", %s, %s, %s },\n' % (n, k[2], k[3], lit(UNESC(v[1]))))
    f.write('};\n\n')
    f.write('static const LT_CALNUMBER g_CalendarNumbers[] =\n{\n')
    for n in locales:
        for k in sorted((k for k in oa if k[0] == 'CN' and k[1] == n), key=lambda k: (int(k[2]), int(k[3]))):
            v = oa[k]
            if not agree(k, v, 'CN'): continue
            f.write('    { L"%s", %s, %s, %s },\n' % (n, k[2], k[3], v[0]))
    f.write('};\n\n')
    # calendars of a locale, enumeration lists
    f.write('static const LT_CALLIST g_CalendarLists[] =\n{\n')
    for n in locales:
        k = ('CALS', n)
        if k in oa and agree(k, oa[k], 'CALS'):
            f.write('    { L"%s", "%s" },\n' % (n, oa[k][0]))
    f.write('};\n\n')
    TAGS = {'SERASTRING': 4, 'SABBREVERASTRING': 57, 'SSHORTDATE': 5, 'SLONGDATE': 6, 'SYEARMONTH': 47, 'IYEAROFFSETRANGE': 3,
            'SCALNAME': 2, 'SMONTHDAY': 56}
    f.write('/* Values of EnumCalendarInfoExEx, NUL-separated, in the order of Windows */\n')
    f.write('static const LT_ENUM g_CalendarEnums[] =\n{\n')
    for n in locales:
        groups = collections.OrderedDict()
        for k in oa:
            if k[0] == 'ECI' and k[1] == n and k[3] != 'ERR' and k[4] != 'ERR':
                groups.setdefault((k[2], int(k[3])), []).append(k)
        for (tag, cal), ks in sorted(groups.items(), key=lambda x: (x[0][1], TAGS[x[0][0]])):
            ks.sort(key=lambda k: int(k[4]))
            vals = [UNESC(oa[k][0]) for k in ks]
            ok = len(vals) == sum(1 for k in na if k[0] == 'ECI' and k[1] == n and k[2] == tag and k[3] == str(cal) and k[4] != 'ERR')
            ok = ok and all(na.get(k) == oa[k] for k in ks)
            if not ok:
                gap['ECI'] += 1; gaps.write('ECI\t%s\t%s\t%d\t| windows: %s\n' % (n, tag, cal, vals)); continue
            kept['ECI'] += 1
            f.write('    { L"%s", %d, %d, %d, %s },\n' % (n, cal, TAGS[tag], len(vals), ' '.join(lit(v) + ' L"\\0"' for v in vals)))
    f.write('};\n\n')
    f.write('/* EnumDateFormatsExEx: each entry is led by the calendar of the callback */\n')
    f.write('static const LT_ENUM g_DateFormatEnums[] =\n{\n')
    FLAGS = {'SHORT': 1, 'LONG': 2, 'YEARMONTH': 8}
    for n in locales:
        for tag, fl in FLAGS.items():
            ks = sorted((k for k in oa if k[0] == 'EDF' and k[1] == n and k[2] == tag and k[3] != 'ERR'), key=lambda k: int(k[4]))
            if not ks: continue
            vals = [(int(k[3]), UNESC(oa[k][0])) for k in ks]
            nks = sorted((k for k in na if k[0] == 'EDF' and k[1] == n and k[2] == tag and k[3] != 'ERR'), key=lambda k: int(k[4]))
            if [(int(k[3]), UNESC(na[k][0])) for k in nks] != vals:
                gap['EDF'] += 1; gaps.write('EDF\t%s\t%s\t| windows: %s\n' % (n, tag, vals)); continue
            kept['EDF'] += 1
            f.write('    { L"%s", 0, %d, %d, %s },\n' % (n, fl, len(vals), ' '.join(lit(chr(c) + v) + ' L"\\0"' for c, v in vals)))
    f.write('};\n\n')
    f.write('static const LT_ENUM g_TimeFormatEnums[] =\n{\n')
    for n in locales:
        ks = sorted((k for k in oa if k[0] == 'ETF' and k[1] == n and k[3] != 'ERR'), key=lambda k: int(k[3]))
        if not ks: continue
        vals = [UNESC(oa[k][0]) for k in ks]
        nks = sorted((k for k in na if k[0] == 'ETF' and k[1] == n and k[3] != 'ERR'), key=lambda k: int(k[3]))
        if [UNESC(na[k][0]) for k in nks] != vals:
            gap['ETF'] += 1; gaps.write('ETF\t%s\t| windows: %s\n' % (n, vals)); continue
        kept['ETF'] += 1
        f.write('    { L"%s", 0, 0, %d, %s },\n' % (n, len(vals), ' '.join(lit(v) + ' L"\\0"' for v in vals)))
    f.write('};\n\n')
    # name functions: names Windows knows as real locales and nitro answers the same
    f.write('/* LocaleNameToLCID with flags 0 and with LOCALE_ALLOW_NEUTRAL_NAMES, ResolveLocaleName and LCIDToLocaleName of the LCID */\n')
    f.write('static const LT_NAME g_LocaleNames[] =\n{\n')
    for k in on:
        if k[0] != 'ALL': continue
        v = on[k]
        if v[0] in ('0x0', '0x1000') or v[1] == '0x1000': continue
        k2 = ('ALL2', k[1])
        if nn.get(k) != v or nn.get(k2) != on.get(k2):
            gap['ALL'] += 1; gaps.write('ALL\t%s\t| windows: %s %s | nitro: %s %s\n' % (k[1], v, on.get(k2), nn.get(k), nn.get(k2))); continue
        kept['ALL'] += 1
        a, b, rl, rn = v[0], v[1], v[2], UNESC(v[3])
        r2 = on[k2]
        f.write('    { L"%s", %s, %s, %s, %s, %s, %s, %s },\n' % (UNESC(k[1]), a, b, rn and lit(rn) or 'L""', r2[0], lit(UNESC(r2[1])), r2[2], lit(UNESC(r2[3]))))
    f.write('};\n\n')
    f.write('/* GetUserDefaultLocaleName and the LCIDs that LCIDToLocaleName takes as they are */\n')
    f.write('static const LT_LCIDNAME g_LcidNames[] =\n{\n')
    for k in on:
        if k[0] != 'L2LN': continue
        v = on[k]
        if nn.get(k) != v:
            gap['L2LN'] += 1; gaps.write('L2LN\t%s\t| windows: %s | nitro: %s\n' % (k[1], v, nn.get(k))); continue
        kept['L2LN'] += 1
        f.write('    { %s, %s, %s, %s },\n' % (k[1], v[0], lit(UNESC(v[1])), v[2]))
    f.write('};\n')
    f.close(); gaps.close()
    print('kept', dict(kept)); print('gaps', dict(gap))
main()
