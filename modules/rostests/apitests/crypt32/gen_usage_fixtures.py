# Needs python3 and openssl 3.4 or later (x509 -not_before). All keys and certificates are made
# here, for the test only, in a temporary directory that is deleted on exit:
#
#   UsRootA    self-signed root A
#   UsRootB    self-signed root B
#   UsCrossB   root B's subject and key, issued by root A (a cross certificate)
#   UsLeaf     end certificate issued by B, for server authentication and code signing
#   UsLeafCs   end certificate issued by B, for code signing only

import base64, os, shutil, subprocess, sys, tempfile

W = None


def sh(*a, **k):
    return subprocess.run(a, check=True, capture_output=True, **k).stdout


def mkcert(name, cn, ca=None, key=None, ext=None, serial=1):
    """ca None: self-signed.  key: use this key (name) instead of one of its own."""
    key = key or name
    if not os.path.exists(f'{W}/{key}.key'):
        sh('openssl', 'genrsa', '-out', f'{W}/{key}.key', '2048')
    open(f'{W}/{name}.cnf', 'w').write('\n'.join(ext) + '\n')
    csr = sh('openssl', 'req', '-new', '-key', f'{W}/{key}.key', '-subj', f'/CN={cn}')
    cmd = ['openssl', 'x509', '-req', '-in', '-', '-not_before', '20200101000000Z', '-not_after',
           '20990101000000Z', '-sha256', '-set_serial', str(serial), '-extfile', f'{W}/{name}.cnf']
    if ca is None:
        cmd += ['-signkey', f'{W}/{key}.key']
    else:
        cmd += ['-CA', f'{W}/{ca}.crt', '-CAkey', f'{W}/{ca}.key']
    open(f'{W}/{name}.crt', 'wb').write(sh(*cmd, input=csr))
    return sh('openssl', 'x509', '-in', f'{W}/{name}.crt', '-outform', 'DER')


def b64(name, data, out):
    s = base64.b64encode(data).decode()
    out.write(f'static const char {name}[] =\n')
    for i in range(0, len(s), 76):
        out.write(f'    "{s[i:i + 76]}"\n')
    out.write('    ;\n\n')


def generate(outpath):
    ca = ['basicConstraints=critical,CA:TRUE', 'keyUsage=critical,keyCertSign,cRLSign',
          'subjectKeyIdentifier=hash']
    root_a = mkcert('roota', 'ReactOS test usage root A', ext=ca, serial=1)
    root_b = mkcert('rootb', 'ReactOS test usage root B', ext=ca, serial=2)
    cross_b = mkcert('crossb', 'ReactOS test usage root B', ca='roota', key='rootb',
                     ext=ca + ['authorityKeyIdentifier=keyid'], serial=3)
    leaf = mkcert('leaf', 'ReactOS test usage leaf', ca='rootb',
                  ext=['basicConstraints=critical,CA:FALSE', 'keyUsage=critical,digitalSignature',
                       'extendedKeyUsage=serverAuth,codeSigning', 'authorityKeyIdentifier=keyid'],
                  serial=4)
    leaf_cs = mkcert('leafcs', 'ReactOS test usage code signing leaf', ca='rootb',
                     ext=['basicConstraints=critical,CA:FALSE', 'keyUsage=critical,digitalSignature',
                          'extendedKeyUsage=codeSigning', 'authorityKeyIdentifier=keyid'],
                     serial=5)
    with open(outpath, 'w') as o:
        o.write('/* Generated by gen_usage_fixtures.py, do not edit. Test data only: throwaway\n'
                ' * certificates made for the test. */\n\n')
        b64('UsRootA', root_a, o)
        b64('UsRootB', root_b, o)
        b64('UsCrossB', cross_b, o)
        b64('UsLeaf', leaf, o)
        b64('UsLeafCs', leaf_cs, o)
    print('wrote', outpath)


def main(outpath):
    global W
    W = tempfile.mkdtemp(prefix='usfix')
    try:
        generate(outpath)
    finally:
        shutil.rmtree(W, ignore_errors=True)


if __name__ == '__main__':
    main(sys.argv[1])
