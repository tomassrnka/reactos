#!/usr/bin/env python3
"""Generates pkcs12_fixtures.h for the crypt32 PKCS #12 test (pkcs12.c).

Everything is made from throw-away keys created by this script; the private keys are public
test data and protect nothing. Needs the openssl command line tool (3.x) and python3 with the
'cryptography' package.

    gen_pkcs12_fixtures.py [--windows-made FILE] > pkcs12_fixtures.h

FILE, if given, is a PFX produced by Windows' own PFXExportCertStoreEx (password "pw", certificate
with its RSA key, exported with EXPORT_PRIVATE_KEYS); see the comment in pkcs12.c. It is embedded
as 'windows'. '--dump DIR' writes the raw .pfx files instead of the header.
"""
import subprocess, sys, tempfile, os, datetime

from cryptography import x509
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import rsa
from cryptography.hazmat.primitives.serialization import pkcs12
from cryptography.x509.oid import NameOID

def make_cert(cn, key, issuer_cn=None, issuer_key=None):
    name = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, cn)])
    issuer = x509.Name([x509.NameAttribute(NameOID.COMMON_NAME, issuer_cn or cn)])
    now = datetime.datetime(2026, 1, 1)
    return (x509.CertificateBuilder().subject_name(name).issuer_name(issuer).public_key(key.public_key())
            .serial_number(x509.random_serial_number()).not_valid_before(now)
            .not_valid_after(datetime.datetime(2126, 1, 1))
            .sign(issuer_key or key, hashes.SHA256()))

def pem_key(k):
    return k.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8, serialization.NoEncryption())

def pem_cert(c):
    return c.public_bytes(serialization.Encoding.PEM)

def tamper_mac(pfx):
    """flip a bit in the MAC digest: MacData is the last element, DigestInfo is its first"""
    def tlv(d, o):
        t = d[o]; l = d[o + 1]; h = 2
        if l & 0x80:
            n = l & 0x7f; l = int.from_bytes(d[o + 2:o + 2 + n], 'big'); h = 2 + n
        return t, o + h, l
    _, o, l = tlv(pfx, 0)              # PFX
    _, o2, l2 = tlv(pfx, o)            # version
    o = o2 + l2
    _, o2, l2 = tlv(pfx, o)            # authSafe
    o = o2 + l2
    _, md, _ = tlv(pfx, o)             # MacData content
    _, di, l2 = tlv(pfx, md)           # DigestInfo
    _, al, l3 = tlv(pfx, di)           # AlgorithmIdentifier
    _, dg, l4 = tlv(pfx, di + (al - di) + l3)   # digest OCTET STRING
    b = bytearray(pfx); b[dg + l4 - 1] ^= 1
    return bytes(b)

def main():
    wm = None
    dump = None
    if len(sys.argv) > 2 and sys.argv[1] == '--windows-made':
        wm = open(sys.argv[2], 'rb').read()
    if len(sys.argv) > 2 and sys.argv[1] == '--dump':
        dump = sys.argv[2]
    key = rsa.generate_private_key(65537, 1024)
    cakey = rsa.generate_private_key(65537, 1024)
    ca = make_cert('ReactOS PKCS12 test CA', cakey)
    leaf = make_cert('ReactOS PKCS12 test', key, 'ReactOS PKCS12 test CA', cakey)
    out = {}
    with tempfile.TemporaryDirectory() as d:
        def w(n, b): open(os.path.join(d, n), 'wb').write(b); return os.path.join(d, n)
        k, c, cc = w('k.pem', pem_key(key)), w('c.pem', pem_cert(leaf)), w('ca.pem', pem_cert(ca))
        def ossl(name, pw, *extra, chain=True):
            f = os.path.join(d, name + '.pfx')
            cmd = ['openssl', 'pkcs12', '-export', '-inkey', k, '-in', c, '-passout', 'pass:' + pw, '-out', f]
            if chain: cmd += ['-certfile', cc]
            subprocess.check_call(cmd + list(extra), stderr=subprocess.DEVNULL)
            out[name] = open(f, 'rb').read()
        ossl('aes256sha256', 'pw', '-name', 'ReactOS test')
        ossl('legacy', 'pw', '-legacy', '-name', 'ReactOS test')
        ossl('des3', 'pw', '-certpbe', 'PBE-SHA1-3DES', '-keypbe', 'PBE-SHA1-3DES', '-macalg', 'sha1', chain=False)
        ossl('emptypw', '', '-legacy', chain=False)
        ossl('nomac', 'pw', '-legacy', '-nomac', chain=False)
        ossl('itermax', 'pw', '-legacy', '-iter', '600000', '-macalg', 'sha1', chain=False)
        ossl('iterover', 'pw', '-legacy', '-iter', '600001', '-macalg', 'sha1', chain=False)
        out['plain'] = pkcs12.serialize_key_and_certificates(b'plain', key, leaf, None, serialization.NoEncryption())
        out['badmac'] = tamper_mac(out['legacy'])
        if wm: out['windows'] = wm
        out['_leaf_der'] = leaf.public_bytes(serialization.Encoding.DER)
    if dump:
        for name, data in out.items():
            open(os.path.join(dump, name + '.pfx'), 'wb').write(data)
        return
    print('/* Generated by gen_pkcs12_fixtures.py. Throw-away test keys only; do not edit. */\n')
    for name, data in out.items():
        n = name if not name.startswith('_') else name[1:]
        print('static const BYTE pfx_%s[] =\n{' % n)
        for i in range(0, len(data), 12):
            print('    ' + ', '.join('0x%02x' % b for b in data[i:i + 12]) + ',')
        print('};\n')

main()
