#!/usr/bin/env python3
"""marksizes.py SRCDIR: write the pixel-fitted marks mark-16/20/24/32.svg into SRCDIR.
Every edge of the frame, the panes and the light lies on the pixel grid of its size, so the small icons
stay sharp; the master mark.svg is used from 48 px up. Edit the table below, then rerun."""
import os, sys

# N: (frame outer x0, y0, x1, y1, frame thickness, corner radius, mullion width, light width,
#     casement overhang above/below the frame, sash width at the free edge, highlight)
SIZES = {
    16: (1, 1, 15, 15, 1, 1.0, 1, 2, 1, 1, True),
    20: (1, 1, 19, 19, 1, 1.5, 1, 3, 1, 1, True),
    24: (1, 2, 23, 22, 2, 2.0, 1, 3, 2, 2, True),
    32: (2, 3, 30, 29, 2, 3.0, 2, 4, 3, 2, True),
}

def svg(n, p):
    x0, y0, x1, y1, t, r, mw, lw, oh, sw, hl = p
    ix0, iy0, ix1, iy1 = x0 + t, y0 + t, x1 - t, y1 - t          # inner opening
    iw = ix1 - ix0
    paneL = (iw - mw - lw - sw) * 5 // 9                           # closed pane width
    mx0 = ix0 + paneL; mx1 = mx0 + mw                              # mullion
    fe = mx1 + lw                                                  # free edge of the open casement
    oy0, oy1 = y0 - oh, y1 + oh                                    # the free edge is taller (nearer)
    g = []
    frame = 'fill="url(#frame)"' if n >= 32 else 'class="f-deep"'
    g.append(f'<rect x="{mx1}" y="{iy0}" width="{ix1 - mx1}" height="{iy1 - iy0}" fill="url(#light)"/>')
    g.append(f'<rect x="{ix0}" y="{iy0}" width="{paneL}" height="{iy1 - iy0}" fill="url(#glassL)"/>')
    if hl:
        h = iy1 - iy0
        a, b = iy0 + round(h * 0.55), iy0 + round(h * 0.25)
        w = max(1, round(h * 0.14))
        g.append(f'<path d="M{ix0} {a} L{mx0} {b} V{b + w} L{ix0} {a + w} Z" class="f-white" opacity="0.45"/>')
    # casement: sash outline, glass, then the dark thickness line on the free edge
    g.append(f'<path d="M{fe} {oy0} L{ix1} {iy0} V{iy1} L{fe} {oy1} Z" class="f-deep"/>')
    gx0 = fe + sw
    k = (iy0 - oy0) / max(1, ix1 - fe)
    gt0, gb0 = oy0 + k * sw + 1, oy1 - k * sw - 1
    if n <= 16:
        gt0, gb0 = iy0, iy1
    g.append(f'<path d="M{gx0} {gt0:.2f} L{ix1} {iy0} V{iy1} L{gx0} {gb0:.2f} Z" fill="url(#glassR)"/>')
    if hl and ix1 - gx0 >= 3:
        h = iy1 - iy0; a, b = iy0 + round(h * 0.5), iy0 + round(h * 0.32); w = max(1, round(h * 0.12))
        g.append(f'<path d="M{gx0} {a} L{ix1} {b} V{b + w} L{gx0} {a + w} Z" class="f-white" opacity="0.35"/>')
    # the frame is drawn over the casement so its outline stays whole; only the free edge stands out
    g.append(f'<path {frame} fill-rule="evenodd" d="M{x0 + r} {y0} H{x1 - r} A{r} {r} 0 0 1 {x1} {y0 + r} '
             f'V{y1 - r} A{r} {r} 0 0 1 {x1 - r} {y1} H{x0 + r} A{r} {r} 0 0 1 {x0} {y1 - r} V{y0 + r} A{r} {r} 0 0 1 {x0 + r} {y0} Z '
             f'M{ix0} {iy0} V{iy1} H{mx0} V{iy0} Z M{mx1} {iy0} V{iy1} H{ix1} V{iy0} Z"/>')
    g.append(f'<rect x="{fe}" y="{oy0}" width="1" height="{oy1 - oy0}" class="f-ink"/>')
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<?xml-stylesheet type="text/css" href="palette.css"?>
<!-- AjarOS mark fitted to the {n} px grid; generated by media/branding/tools/marksizes.py -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" width="{n}" height="{n}">
  <defs>
    <linearGradient id="frame" x1="0" y1="0" x2="0" y2="1"><stop offset="0" class="c-harbor"/><stop offset="0.6" class="c-deep"/></linearGradient>
    <linearGradient id="glassL" x1="0" y1="0" x2="0" y2="1"><stop offset="0" class="c-mist"/><stop offset="1" class="c-sky"/></linearGradient>
    <linearGradient id="glassR" x1="0" y1="0" x2="1" y2="1"><stop offset="0" class="c-sky"/><stop offset="1" class="c-harbor"/></linearGradient>
    <linearGradient id="light" x1="0" y1="0" x2="0" y2="1"><stop offset="0" class="c-glow"/><stop offset="1" class="c-lamp"/></linearGradient>
  </defs>
  {chr(10).join('  ' + x for x in g).strip()}
</svg>
'''

def reverse(text):
    """The same fitted mark for dark grounds: light frame and sash, darker glass (as mark-reverse.svg)."""
    text = text.replace('fitted to the', 'for dark grounds fitted to the')
    text = text.replace('<stop offset="0" class="c-harbor"/><stop offset="0.6" class="c-deep"/>', '<stop offset="0" class="c-white"/><stop offset="1" class="c-mist"/>')
    text = text.replace('<stop offset="0" class="c-mist"/><stop offset="1" class="c-sky"/>', '<stop offset="0" class="c-sky"/><stop offset="1" class="c-harbor"/>')
    text = text.replace('<stop offset="0" class="c-sky"/><stop offset="1" class="c-harbor"/></linearGradient>\n    <linearGradient id="light"',
                        '<stop offset="0" class="c-harbor"/><stop offset="1" class="c-deep"/></linearGradient>\n    <linearGradient id="light"')
    return text.replace('class="f-deep"', 'class="f-mist"').replace('class="f-ink"', 'class="f-sky"')

def glyph(n, p):
    """One-colour mark for theme Start buttons and other monochrome uses: white with opacities; the light
    is the brightest area, separated from the casement by a one-pixel slit."""
    x0, y0, x1, y1, t, r, mw, lw, oh, sw, hl = p
    ix0, iy0, ix1, iy1 = x0 + t, y0 + t, x1 - t, y1 - t
    iw = ix1 - ix0
    paneL = (iw - mw - lw - sw) * 5 // 9
    mx0 = ix0 + paneL; mx1 = mx0 + mw; fe = mx1 + lw
    oy0, oy1 = y0 - oh, y1 + oh
    g = [f'<rect x="{ix0}" y="{iy0}" width="{paneL}" height="{iy1 - iy0}" class="f-white" opacity="0.3"/>',
         f'<rect x="{mx1}" y="{iy0}" width="{lw - 1}" height="{iy1 - iy0}" class="f-white"/>',
         f'<rect x="{fe + 1}" y="{iy0}" width="{ix1 - fe - 1}" height="{iy1 - iy0}" class="f-white" opacity="0.6"/>',
         f'<path class="f-white" fill-rule="evenodd" d="M{x0 + r} {y0} H{x1 - r} A{r} {r} 0 0 1 {x1} {y0 + r} '
         f'V{y1 - r} A{r} {r} 0 0 1 {x1 - r} {y1} H{x0 + r} A{r} {r} 0 0 1 {x0} {y1 - r} V{y0 + r} A{r} {r} 0 0 1 {x0 + r} {y0} Z '
         f'M{ix0} {iy0} V{iy1} H{mx0} V{iy0} Z M{mx1} {iy0} V{iy1} H{ix1} V{iy0} Z"/>',
         f'<rect x="{fe}" y="{oy0}" width="1" height="{oy1 - oy0}" class="f-white"/>']
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<?xml-stylesheet type="text/css" href="palette.css"?>
<!-- AjarOS one-colour mark fitted to the {n} px grid; generated by media/branding/tools/marksizes.py -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {n} {n}" width="{n}" height="{n}">
  {chr(10).join('  ' + x for x in g).strip()}
</svg>
'''

if __name__ == '__main__':
    d = sys.argv[1]
    for n, p in SIZES.items():
        open(os.path.join(d, f'mark-{n}.svg'), 'w').write(svg(n, p))
        open(os.path.join(d, f'mark-reverse-{n}.svg'), 'w').write(reverse(svg(n, p)))
        print(f'mark-{n}.svg mark-reverse-{n}.svg')
        if n <= 24:
            open(os.path.join(d, f'mark-glyph-{n}.svg'), 'w').write(glyph(n, p))
            print(f'mark-glyph-{n}.svg')
