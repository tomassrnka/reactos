#!/usr/bin/env python3
"""wordmark.py SRCDIR: write the AjarOS wordmark (wordmark.svg for light grounds, wordmark-reverse.svg for
dark grounds) into SRCDIR as outlines of Figtree (SIL OFL 1.1, SRCDIR/fonts): "Ajar" at weight 650, "OS"
at weight 400, hand-kerned; the dot of the j is a small lamp-coloured pane, the brand's warm accent."""
import os, sys
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

SRC = sys.argv[1]
FONT = os.path.join(SRC, 'fonts', 'Figtree-VariableFont_wght.ttf')
PARTS = [('Ajar', 650), ('OS', 400)]
KERN = {('A', 'j'): -10, ('j', 'a'): 10, ('a', 'r'): 0, ('r', 'O'): 10, ('O', 'S'): -6}   # font units
TRACK = 6                                                                                  # font units per gap
DOT_SCALE = 1.1
COLOURS = {'wordmark.svg': ('f-deep', 'f-harbor', 'f-lamp'), 'wordmark-reverse.svg': ('f-white', 'f-sky', 'f-lamp')}

def contours(rec):
    out, cur = [], []
    for op, args in rec.value:
        cur.append((op, args))
        if op in ('closePath', 'endPath'):
            out.append(cur); cur = []
    return out

def path_of(ops, dx, gs):
    sp = SVGPathPen(gs)
    tp = TransformPen(sp, (1, 0, 0, -1, dx, 0))
    for op, args in ops:
        getattr(tp, op)(*args)
    return sp.getCommands()

def bounds(ops, gs):
    bp = BoundsPen(gs)
    for op, args in ops: getattr(bp, op)(*args)
    return bp.bounds

fonts = {w: instancer.instantiateVariableFont(TTFont(FONT), {'wght': w}) for _, w in PARTS}
x = 0; prev = None; paths = []      # (part index, d)
dot = None
xh = fonts[650]['OS/2'].sxHeight
for pi, (text, w) in enumerate(PARTS):
    f = fonts[w]; gs = f.getGlyphSet(); cmap = f.getBestCmap()
    for ch in text:
        if prev: x += KERN.get((prev, ch), 0) + TRACK
        gn = cmap[ord(ch)]; rec = DecomposingRecordingPen(gs); gs[gn].draw(rec)
        keep = []
        for c in contours(rec):
            b = bounds(c, gs)
            if ch == 'j' and b and b[1] > xh * 0.9:
                dot = (x + b[0], b[1], x + b[2], b[3])
                continue
            keep += c
        paths.append((pi, path_of(keep, x, gs)))
        x += f['hmtx'][gn][0]; prev = ch
asc = fonts[650]['OS/2'].sCapHeight
f = fonts[650]; gs = f.getGlyphSet(); bj = gs[f.getBestCmap()[ord('j')]]; bp = BoundsPen(gs); bj.draw(bp)
ymin = bp.bounds[1]
top = max(asc, dot[3]) + 2
cx, cy = (dot[0] + dot[2]) / 2, (dot[1] + dot[3]) / 2
s = max(dot[2] - dot[0], dot[3] - dot[1]) * DOT_SCALE
r = s * 0.2
W = x
for name, (c1, c2, c3) in COLOURS.items():
    body = '\n'.join(f'  <path class="{c1 if pi == 0 else c2}" d="{d}"/>' for pi, d in paths)
    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<?xml-stylesheet type="text/css" href="palette.css"?>
<!-- AjarOS wordmark, outlines of Figtree (SIL OFL 1.1); generated by media/branding/tools/wordmark.py.
     Units: font units; the baseline is y=0, the cap height is y=-{asc}. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 {-top:.0f} {W:.0f} {top - ymin:.0f}" width="{W / 10:.1f}" height="{(top - ymin) / 10:.1f}">
{body}
  <rect class="{c3}" x="{cx - s / 2:.1f}" y="{-(cy + s / 2):.1f}" width="{s:.1f}" height="{s:.1f}" rx="{r:.1f}"/>
</svg>
'''
    open(os.path.join(SRC, name), 'w').write(svg)
    print(name, 'width', round(W), 'cap', asc, 'descender', ymin)
